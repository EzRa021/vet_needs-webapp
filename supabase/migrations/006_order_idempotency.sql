-- ============================================================
-- 006_order_idempotency.sql
-- Stops a double-clicked "Place order" from creating duplicate
-- pending orders.
--
-- Why this has to live in the database: the API can check "does an
-- order with this key already exist?" before inserting, but two
-- requests fired 20ms apart both run that check before either
-- inserts, so both see nothing and both insert. Only a unique
-- constraint can decide a winner. The API catches the resulting
-- 23505 and returns the order the winner created, so the loser's
-- shopper still sees success.
-- ============================================================

-- Idempotency key: generated by the browser, stable for one checkout
-- attempt and regenerated when the cart changes.
alter table public.orders
  add column if not exists idempotency_key text;

-- Scoped to user_id so two shoppers can never collide on a key, and
-- partial so the column stays optional — existing rows are null, and
-- null is not unique in Postgres anyway.
create unique index if not exists orders_user_idempotency_key_idx
  on public.orders (user_id, idempotency_key)
  where idempotency_key is not null;

comment on column public.orders.idempotency_key is
  'Client-generated key for one checkout attempt. Unique per user (partial index) so a retried or double-clicked submit returns the original order instead of creating another.';
